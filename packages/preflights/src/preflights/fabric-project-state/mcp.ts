// Faithful TypeScript ports of the mcp-atlassian response transformations
// that shape the Jira data the Fabric coordinator Python actually digests.
//
// The deployed server is mcp-atlassian==0.23.1 (rehor proxy/Dockerfile pin;
// PyPI sdist sha256 6b57391928887f5334fe854073b09e3a49bb7dae0d55a1b1276f4d910607a0f1).
// Its jira_search/jira_get_issue tools return
// json.dumps(JiraIssue.to_simplified_dict()) (servers/jira.py:703,735,856),
// so the Fabric Python runner never sees raw REST shapes. The ports below
// mirror the exact 0.23.1 source so a REST read can be normalized into the
// same values before hashing; the golden fixtures in
// test/fixtures/project-state-parity/ are generated by executing the real
// Python server models plus the real Fabric project_coordinator.py.
//
// Sources (sdist paths, mcp_atlassian-0.23.1):
//   - mcpAdfToText               models/jira/adf.py:517-602 (adf_to_text)
//   - processCustomFieldValue models/jira/issue.py:711-741
//     (_process_custom_field_value) plus the {"value": ...} wrapper built at
//     models/jira/issue.py:454-463 for every customfield_* key
//   - simplifyLinks           models/jira/link.py:17-285 (JiraIssueLinkType,
//     JiraLinkedIssueFields, JiraLinkedIssue, JiraIssueLink) and the
//     {"name"}-only status/priority/issuetype shapes from models/jira/common.py
//   - description handling    models/jira/issue.py:282-288 (dict -> adf_to_text,
//     other values pass through) and the truthy gate at :539-540
//
// Divergences are deliberate and fail-closed only:
//   - recursion is depth-capped well below Python's limit; absurdly deep
//     documents throw instead of exhausting the stack
//   - values Python would crash on inside list joins (non-string ADF text)
//     throw here as well, matching the server's tool-error outcome

import { isRecord, pyTruthy } from "../jira-common/shapes.js";
import { assertNumber } from "./numbers.js";

/**
 * Python str() for JSON scalars (str(None) is "None", booleans capitalize).
 * Objects and non-safe integral numbers fail closed: Python would repr the
 * former and print the latter exactly, neither of which String() reproduces.
 */
export function pyScalarStr(value: string | number | boolean | null): string {
  if (typeof value === "string") return value;
  if (value === null) return "None";
  if (typeof value === "boolean") return value ? "True" : "False";
  if (typeof value === "number") {
    if (Number.isInteger(value) && !Number.isSafeInteger(value))
      throw new Error("Unsupported large number in Python str() coercion");
    return String(value);
  }
  throw new Error("Unsupported object in Python str() coercion");
}

const MAX_DEPTH = 200;

// Thin adapter over the shared isRecord guard (snapshot.ts cannot be imported
// here without an import cycle).
const record = (value: unknown): Record<string, unknown> | undefined =>
  isRecord(value) ? value : undefined;

/** mcp_atlassian ADF "attrs": missing means {}, a present non-object crashes Python. */
function adfAttrs(node: Record<string, unknown>): Record<string, unknown> {
  if (node.attrs === undefined) return {};
  const attrs = record(node.attrs);
  if (!attrs) throw new Error("Invalid ADF attrs");
  return attrs;
}

// datetime.fromtimestamp(int(timestamp) / 1000, tz=timezone.utc) is limited to
// years 1..9999; outside that (or for unparsable values) Python falls back to
// str(timestamp) (models/jira/adf.py:563-573). The year is printed without
// zero padding: the deployed server runs on glibc (ubi9 proxy container),
// where %Y renders 481 as "481" — verified against python:3.11-slim; macOS
// Python pads to "0481", so goldens must not carry year<1000 dates.
const MIN_DATE_MS = -62135596800000;
const MAX_DATE_MS = 253402300799999;

// Python int() for strings: surrounding whitespace and single underscores
// between digits are accepted (int(" 42 ") == 42, int("1_000") == 1000);
// anything else raises ValueError and the date falls back to str(timestamp).
const INT_STRING = /^[+-]?(?:\d+(?:_\d+)*)$/;

function pyIntValue(value: string): number | undefined {
  const trimmed = value.trim();
  if (!INT_STRING.test(trimmed)) {
    // Python also parses non-ASCII decimal digits (int("٤٢") == 42); that
    // cannot be reproduced here, so fail closed instead of hashing a
    // different fallback string.
    for (const ch of trimmed) {
      if ((ch.codePointAt(0) ?? 0) > 0x7f && /\p{Nd}/u.test(ch))
        throw new Error("Unsupported Unicode digits in ADF date");
    }
    return undefined;
  }
  return Number(trimmed.replace(/_/g, ""));
}

function adfDateText(attrs: Record<string, unknown>): string {
  const timestamp = attrs.timestamp;
  let ms: number | undefined;
  if (typeof timestamp === "number" && Number.isFinite(timestamp)) {
    // Python int() truncates toward zero; the result is exact for the safe
    // integers that reach the in-range path.
    ms = Math.trunc(timestamp);
  } else if (typeof timestamp === "boolean") {
    ms = timestamp ? 1 : 0;
  } else if (typeof timestamp === "string") {
    const parsed = pyIntValue(timestamp);
    if (parsed !== undefined) ms = parsed;
  }
  if (ms === undefined || ms < MIN_DATE_MS || ms > MAX_DATE_MS) {
    // str(timestamp) fallback. For numbers this must fail closed when the
    // Python text cannot be reproduced: float lexemes format differently
    // (str(1e15) is "1000000000000000.0") and non-safe integers lose digits.
    if (typeof timestamp === "number") assertNumber(attrs, "timestamp", timestamp);
    return pyScalarStr(timestamp as string | number | boolean | null);
  }
  const date = new Date(ms);
  const month = `${date.getUTCMonth() + 1}`.padStart(2, "0");
  const day = `${date.getUTCDate()}`.padStart(2, "0");
  return `${date.getUTCFullYear()}-${month}-${day}`;
}

/**
 * Port of mcp-atlassian 0.23.1 adf_to_text: ADF content to plain text.
 * Returns null for empty content, the raw value for scalar-ish nodes Python
 * passes through, and strings otherwise. Nested list items are joined with
 * "\n" and only truthy texts survive, exactly like the Python original.
 */
export function mcpAdfToText(node: unknown, depth = 0): unknown {
  if (depth > MAX_DEPTH) throw new Error("ADF nesting too deep");
  if (node === null || node === undefined) return null;
  if (typeof node === "string") return node;
  if (Array.isArray(node)) {
    const texts: string[] = [];
    for (const item of node) {
      const text = mcpAdfToText(item, depth + 1);
      // Python keeps only truthy texts ("if text:"), so 0/""/None drop out.
      if (!pyTruthy(text)) continue;
      // Python "\n".join() raises TypeError on non-string parts; the server
      // turns that into a tool error, so fail closed the same way.
      if (typeof text !== "string") throw new Error("Invalid ADF text");
      texts.push(text);
    }
    return texts.length ? texts.join("\n") : null;
  }
  const item = record(node);
  if (!item) return null;
  const type = item.type;
  if (type === "text") return "text" in item ? item.text : "";
  if (type === "hardBreak") return "\n";
  if (type === "mention") {
    const attrs = adfAttrs(item);
    if (pyTruthy(attrs.text)) return attrs.text;
    const id =
      attrs.id === undefined
        ? "unknown"
        : pyScalarStr(attrs.id as string | number | boolean | null);
    return `@${id}`;
  }
  if (type === "emoji") {
    const attrs = adfAttrs(item);
    if (pyTruthy(attrs.text)) return attrs.text;
    return attrs.shortName === undefined ? "" : attrs.shortName;
  }
  if (type === "date") {
    const attrs = adfAttrs(item);
    return pyTruthy(attrs.timestamp) ? adfDateText(attrs) : "";
  }
  if (type === "status") {
    const attrs = adfAttrs(item);
    const text = "text" in attrs ? pyScalarStr(attrs.text as string | number | boolean | null) : "";
    return `[${text}]`;
  }
  if (type === "inlineCard") {
    const attrs = adfAttrs(item);
    if (pyTruthy(attrs.url)) return attrs.url;
    const data = record(attrs.data);
    if (attrs.data !== undefined && !data) throw new Error("Invalid ADF card data");
    if (data && pyTruthy(data.url)) return data.url;
    return data && data.name !== undefined ? data.name : "";
  }
  if (type === "codeBlock") {
    const code = mcpAdfToText(item.content === undefined ? [] : item.content, depth + 1);
    const text = pyTruthy(code) ? pyScalarStr(code as string | number | boolean | null) : "";
    return `\`\`\`\n${text}\n\`\`\``;
  }
  const content = item.content;
  if (pyTruthy(content)) return mcpAdfToText(content, depth + 1);
  return null;
}

/**
 * Port of mcp-atlassian 0.23.1 _process_custom_field_value: single-select and
 * user-picker style values collapse to their inner "value" (option ids are
 * discarded), reference objects with a "self" URL collapse to their "name",
 * and anything else is preserved. Numbers are lexeme-asserted where they are
 * read so Python's str(int)/str(float) distinction cannot be lost silently.
 */
export function processCustomFieldValue(value: unknown, depth = 0): unknown {
  if (depth > MAX_DEPTH) throw new Error("Custom field nesting too deep");
  if (
    value === null ||
    typeof value === "string" ||
    typeof value === "number" ||
    typeof value === "boolean"
  )
    return value;
  const obj = record(value);
  if (obj) {
    if (Object.hasOwn(obj, "value")) {
      assertNumber(obj, "value", obj.value);
      return obj.value;
    }
    if (Object.hasOwn(obj, "name")) {
      assertNumber(obj, "name", obj.name);
      if (Object.hasOwn(obj, "self")) return obj.name;
      return obj;
    }
    return obj;
  }
  if (Array.isArray(value)) {
    return value.map((item, index) => {
      assertNumber(value, String(index), item);
      return processCustomFieldValue(item, depth + 1);
    });
  }
  throw new Error("Unsupported custom field value");
}

/** The {"value": processed} wrapper 0.23.1 puts on every customfield_* key. */
export function mcpCustomField(raw: unknown): { value: unknown } {
  return { value: processCustomFieldValue(raw) };
}

/**
 * The mcp-atlassian issue description: an ADF object becomes adf_to_text
 * output, every other value passes through untouched, and falsy results are
 * omitted from the tool response entirely (Python then reads them as None).
 */
export function mcpDescription(raw: unknown): unknown {
  const emulated = record(raw) ? mcpAdfToText(raw) : raw;
  return pyTruthy(emulated) ? emulated : undefined;
}

/**
 * The mcp-atlassian issue summary: the model coerces it with str()
 * (models/jira/issue.py:280, summary = str(fields.get("summary", ""))), so a
 * null REST summary arrives as the string "None" and digests that way, while
 * a missing key stays empty. Object summaries fail closed via pyScalarStr.
 */
export function mcpSummaryText(raw: unknown): string {
  return raw === undefined ? "" : pyScalarStr(raw as string | number | boolean | null);
}

// --- Issue link simplification (models/jira/link.py) -----------------------

export type SimplifiedLinkType = {
  id: string;
  name: string;
  inward: string;
  outward: string;
  self?: unknown;
};
export type SimplifiedLinkedIssue = {
  id: string;
  key: string;
  self?: unknown;
  fields?: {
    summary: string;
    status?: { name: string; category?: unknown; color?: unknown };
    priority?: { name: string };
    issuetype?: { name: string };
  };
};
export type SimplifiedLink = {
  id: string;
  type?: SimplifiedLinkType;
  inward_issue?: SimplifiedLinkedIssue;
  outward_issue?: SimplifiedLinkedIssue;
};

function strField(data: Record<string, unknown>, name: string, fallback: string): string {
  return Object.hasOwn(data, name)
    ? pyScalarStr(data[name] as string | number | boolean | null)
    : fallback;
}

function idField(data: Record<string, unknown>, what: string): string {
  if (data.id === null) throw new Error(`Invalid Jira ${what} id`);
  return data.id === undefined ? "0" : pyScalarStr(data.id as string | number | boolean);
}

// JiraIssueLinkType.from_api_response/to_simplified_dict (link.py:17-72).
// Falsy or non-object input yields the model default; the simplified shape
// keeps id/name/inward/outward and only carries "self" when truthy.
function simplifyLinkType(data: unknown): SimplifiedLinkType {
  const obj = pyTruthy(data) ? record(data) : undefined;
  if (!obj) return { id: "0", name: "Unknown", inward: "", outward: "" };
  const result: SimplifiedLinkType = {
    id: idField(obj, "link type"),
    name: strField(obj, "name", "Unknown"),
    inward: strField(obj, "inward", ""),
    outward: strField(obj, "outward", ""),
  };
  return pyTruthy(obj.self) ? { ...result, self: obj.self } : result;
}

// JiraStatus.to_simplified_dict (common.py:189-199) as used by linked fields:
// {"name"} plus the status category name/color when a category is present.
function simplifyStatus(data: unknown): { name: string; category?: unknown; color?: unknown } {
  const obj = pyTruthy(data) ? record(data) : undefined;
  if (!obj) return { name: "Unknown" };
  // A null id fails pydantic validation in the server model (tool error).
  if (obj.id === null) throw new Error("Invalid Jira status id");
  const result: { name: string; category?: unknown; color?: unknown } = {
    name: strField(obj, "name", "Unknown"),
  };
  const rawCategory = obj.statusCategory;
  if (pyTruthy(rawCategory)) {
    // JiraStatusCategory.from_api_response returns the model default
    // ({"name": "Unknown", "colorName": ""}) for truthy non-object input.
    const category = record(rawCategory);
    result.category = category ? strField(category, "name", "Unknown") : "Unknown";
    result.color = category ? strField(category, "colorName", "") : "";
  }
  return result;
}

// JiraLinkedIssueFields (link.py:75-145); priority and issuetype simplify to
// {"name"} only, with the model defaults "None"/"Unknown" (common.py:241-287).
function simplifyLinkedFields(data: unknown): SimplifiedLinkedIssue["fields"] {
  const obj = pyTruthy(data) ? record(data) : undefined;
  if (!obj) return { summary: "" };
  const result: SimplifiedLinkedIssue["fields"] = { summary: strField(obj, "summary", "") };
  if (pyTruthy(obj.status)) result.status = simplifyStatus(obj.status);
  if (pyTruthy(obj.priority)) {
    const priority = record(obj.priority);
    if (priority?.id === null) throw new Error("Invalid Jira priority id");
    result.priority = { name: priority ? strField(priority, "name", "None") : "None" };
  }
  if (pyTruthy(obj.issuetype)) {
    const issueType = record(obj.issuetype);
    if (issueType?.id === null) throw new Error("Invalid Jira issue type id");
    result.issuetype = { name: issueType ? strField(issueType, "name", "Unknown") : "Unknown" };
  }
  return result;
}

// JiraLinkedIssue.from_api_response/to_simplified_dict (link.py:148-209).
function simplifyLinkedIssue(data: unknown): SimplifiedLinkedIssue {
  const obj = pyTruthy(data) ? record(data) : undefined;
  if (!obj) return { id: "0", key: "" };
  const result: SimplifiedLinkedIssue = {
    id: idField(obj, "linked issue"),
    key: strField(obj, "key", ""),
  };
  if (pyTruthy(obj.self)) result.self = obj.self;
  if (pyTruthy(obj.fields)) result.fields = simplifyLinkedFields(obj.fields);
  return result;
}

// JiraIssueLink.from_api_response/to_simplified_dict (link.py:212-285). The
// model layer drops falsy link entries, keeps truthy non-object entries as
// bare defaults, and rewrites inward/outward to snake_case keys.
export function simplifyLinks(links: unknown): SimplifiedLink[] {
  if (!Array.isArray(links)) return [];
  const simplified: SimplifiedLink[] = [];
  for (const entry of links) {
    if (!pyTruthy(entry)) continue;
    const obj = record(entry);
    if (!obj) {
      simplified.push({ id: "0" });
      continue;
    }
    const link: SimplifiedLink = { id: idField(obj, "link") };
    if (pyTruthy(obj.type)) link.type = simplifyLinkType(obj.type);
    if (pyTruthy(obj.inwardIssue)) link.inward_issue = simplifyLinkedIssue(obj.inwardIssue);
    if (pyTruthy(obj.outwardIssue)) link.outward_issue = simplifyLinkedIssue(obj.outwardIssue);
    simplified.push(link);
  }
  return simplified;
}
